#!/usr/bin/env python3
"""Regenerates lib/src/generated.dart from tool/methods.json (copied from the JS SDK's scripts/methods.json).
Usage: python3 tool/generate.py"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
m = json.load(open(ROOT / "tool" / "methods.json"))["generated"]

RESERVED = {"assert","break","case","catch","class","const","continue","default","do","else","enum","extends",
            "false","final","finally","for","if","in","is","new","null","rethrow","return","super","switch",
            "this","throw","true","try","var","void","while","with","toString","hashCode","runtimeType","noSuchMethod"}
CLIENT_MEMBERS = {"request","get","post","put","patch","delete","close","root","baseUrl","apiKey","loginToken",
                  "timeout","pediatric"}

def safe(n):
    return n + "_" if n in RESERVED else n

def pascal(n):
    return n[0].upper() + n[1:]

# Hand-written, typed helpers merged into the generated namespaces.
def crud(base, put=True):
    s = f"""
  Future<dynamic> list({{Map<String, dynamic>? query}}) => _c.get('{base}', query: query);
  Future<dynamic> get(Object id) => _c.get('{base}/${{_enc(id)}}');
  Future<dynamic> create(Map<String, dynamic> body) => _c.post('{base}', body: body);
  Future<dynamic> update(Object id, Map<String, dynamic> body) => _c.patch('{base}/${{_enc(id)}}', body: body);
  Future<dynamic> remove(Object id) => _c.delete('{base}/${{_enc(id)}}');"""
    if put:
        s += f"\n  Future<dynamic> replace(Object id, Map<String, dynamic> body) => _c.put('{base}/${{_enc(id)}}', body: body);"
    return s

HAND = {
  "foods": crud("/foods") + """
  Future<dynamic> lookup([Map<String, dynamic>? query]) => _c.get('/foods/lookup', query: query);
  Future<dynamic> autocomplete(String q, {int maxResults = 4}) =>
      _c.get('/foods/autocomplete', query: {'q': q, 'max_results': maxResults});
  Future<dynamic> categories() => _c.get('/foods/categories');""",
  "exchange": crud("/exchange"),
  "renal": crud("/renal"),
  "formulas": crud("/formulas"),
  "packaged": """
  Future<dynamic> list({Map<String, dynamic>? query}) => _c.get('/packaged', query: query);
  Future<dynamic> submit(Map<String, dynamic> body) => _c.post('/packaged/submit', body: body);
  Future<dynamic> scan(List<String> images) => _c.post('/packaged/scan', body: {'images': images});
  Future<dynamic> update(Object id, Map<String, dynamic> body) => _c.patch('/packaged/${_enc(id)}', body: body);
  Future<dynamic> remove(Object id) => _c.delete('/packaged/${_enc(id)}');""",
  "rag": """
  Future<dynamic> retrieve(String query, {String context = 'both', int topK = 5}) =>
      _c.post('/rag/retrieve', body: {'query': query, 'context': context, 'top_k': topK});
  Future<dynamic> ingest(Map<String, dynamic> body) => _c.post('/rag/ingest', body: body); // admin""",
  "memory": """
  Future<dynamic> write(String sessionId, String content, {String kind = 'fact', String? patientLabel}) =>
      _c.post('/memory/write', body: {
        'session_id': sessionId,
        'content': content,
        'kind': kind,
        if (patientLabel != null) 'patient_label': patientLabel,
      });
  Future<dynamic> recall(String sessionId, String query, {int topK = 5}) =>
      _c.post('/memory/recall', body: {'session_id': sessionId, 'query': query, 'top_k': topK});
  Future<dynamic> consolidate(String sessionId) =>
      _c.post('/memory/consolidate', body: {'session_id': sessionId}); // admin""",
}

out = ["// GENERATED by tool/generate.py from tool/methods.json. Do not edit by hand.",
       "// ignore_for_file: unnecessary_string_interpolations, unnecessary_brace_in_string_interps",
       "", "import 'client.dart';", "", "String _enc(Object v) => Uri.encodeComponent('$v');", ""]
getters = []
namespaces = sorted(set(m) | set(HAND))
for ns in namespaces:
    cls = pascal(ns) + "Api"
    name = safe(ns)
    assert name not in CLIENT_MEMBERS, ns
    getters.append((name, cls, ns))
    out.append(f"/// `{ns}` routes.")
    out.append(f"class {cls} {{")
    out.append(f"  {cls}(this._c);")
    out.append("  final ChakudyaClient _c;")
    if ns in HAND:
        out.append(HAND[ns])
    for mname, route in sorted(m.get(ns, {}).items()):
        method, path = route.split(" ")
        params, seen = [], set()
        for p in re.findall(r"\{(\w+)\}", path):
            v = safe(re.sub(r"_(\w)", lambda x: x.group(1).upper(), p))
            while v in seen: v += "2"
            seen.add(v); params.append((p, v))
        tmpl = path
        for p, v in params:
            tmpl = tmpl.replace("{" + p + "}", "${_enc(" + v + ")}")
        req = "".join(f"Object {v}, " for _, v in params)
        has_body = method in ("POST", "PUT", "PATCH")
        named = "{Map<String, dynamic>? body, Map<String, dynamic>? query}" if has_body else "{Map<String, dynamic>? query}"
        args = "body: body, query: query" if has_body else "query: query"
        sig = f"({req}{named})"
        out.append(f"  /// `{route}`")
        out.append(f"  Future<dynamic> {safe(mname)}{sig} =>")
        out.append(f"      _c.request('{method}', '{tmpl}', {args});")
    out.append("}")
    out.append("")

out.append("/// All namespace accessors, mixed into [ChakudyaClient].")
out.append("mixin ChakudyaNamespaces {")
out.append("  ChakudyaClient get _self => this as ChakudyaClient;")
for name, cls, ns in getters:
    out.append(f"  late final {cls} {name} = {cls}(_self);")
out.append("  /// The API accepts both spellings.")
out.append("  PaediatricApi get pediatric => paediatric;")
out.append("}")
(ROOT / "lib" / "src" / "generated.dart").write_text("\n".join(out) + "\n")
print(len(getters), "namespaces")
